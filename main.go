// okf-mirror reads the Notion Knowledge, Journal, Tasks and Characters databases and
// writes them as an Open Knowledge Format 0.2 bundle. Read-only against Notion.
package main

import (
	"bufio"
	"context"
	"flag"
	"fmt"
	"log"
	"os"
	"os/signal"
	"path/filepath"
	"strings"
	"syscall"
	"time"
)

// version is set by goreleaser (-X main.version=...); "dev" for local builds.
var version = "dev"

func main() {
	log.SetFlags(log.Ldate | log.Ltime)
	if len(os.Args) > 1 && os.Args[1] == "version" {
		fmt.Println("notion-okf-mirror", version)
		return
	}
	if len(os.Args) > 1 && os.Args[1] == "validate" {
		os.Exit(runValidate(os.Args[2:]))
	}
	os.Exit(runMirror(os.Args[1:]))
}

func runValidate(args []string) int {
	fs := flag.NewFlagSet("validate", flag.ExitOnError)
	fs.Usage = func() { fmt.Fprintln(os.Stderr, "usage: notion-okf-mirror validate <bundle-dir>") }
	_ = fs.Parse(args)
	if fs.NArg() != 1 {
		fs.Usage()
		return 2
	}
	findings, err := ValidateDir(fs.Arg(0))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 2
	}
	for _, f := range findings {
		fmt.Println(f)
	}
	if len(findings) > 0 {
		fmt.Printf("%d finding(s)\n", len(findings))
		return 1
	}
	fmt.Println("OK: bundle conforms to OKF 0.2")
	return 0
}

// okflintManifest lets `okflint validate --manifest <out>/okf-base.yaml` gate the bundle.
const okflintManifest = `# Generated by okf-mirror for okflint (https://okf.md/tools/). Do not edit.
okf_version: "0.2"
base:
  name: notion-mirror
  roots:
    - path: okf
  reserved_files:
    index: index.md
    log: log.md
`

func defaultOut() string {
	if v := os.Getenv("OKF_MIRROR_OUT"); v != "" {
		return v
	}
	home, _ := os.UserHomeDir()
	return filepath.Join(home, "okf-mirror")
}

func runMirror(args []string) int {
	fs := flag.NewFlagSet("notion-okf-mirror", flag.ExitOnError)
	out := fs.String("out", defaultOut(), "target directory; the bundle is written to <out>/okf (env OKF_MIRROR_OUT)")
	once := fs.Bool("once", false, "run one pass and exit (otherwise loop every --interval)")
	dryRun := fs.Bool("dry-run", false, "fetch and render, report what would change, write nothing")
	full := fs.Bool("full", false, "refetch every page body, ignoring the cache")
	interval := fs.Duration("interval", 24*time.Hour, "loop interval when not --once")
	tokenFile := fs.String("token-file", "", "file holding NOTION_TOKEN=... (default: env NOTION_TOKEN)")
	noValidate := fs.Bool("no-validate", false, "skip OKF validation of the result")
	fs.Usage = func() {
		fmt.Fprintln(os.Stderr, "usage: notion-okf-mirror [flags]\n       notion-okf-mirror validate <bundle-dir>\n       notion-okf-mirror version")
		fs.PrintDefaults()
	}
	_ = fs.Parse(args)

	token, err := loadToken(*tokenFile)
	if err != nil {
		log.Print(err)
		return 2
	}
	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()
	for {
		code := runOnce(ctx, token, *out, *dryRun, *full, !*noValidate)
		if *once || *dryRun {
			return code
		}
		log.Printf("next run in %s", *interval)
		select {
		case <-ctx.Done():
			return 0
		case <-time.After(*interval):
		}
	}
}

func loadToken(tokenFile string) (string, error) {
	if t := os.Getenv("NOTION_TOKEN"); t != "" && tokenFile == "" {
		return t, nil
	}
	if tokenFile == "" {
		return "", fmt.Errorf("NOTION_TOKEN is not set; export it or pass --token-file")
	}
	f, err := os.Open(tokenFile)
	if err != nil {
		return "", err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(line, "NOTION_TOKEN=") {
			return strings.Trim(strings.TrimPrefix(line, "NOTION_TOKEN="), `"'`), nil
		}
		if line != "" && !strings.HasPrefix(line, "#") && !strings.Contains(line, "=") {
			return line, nil
		}
	}
	return "", fmt.Errorf("no NOTION_TOKEN in %s", tokenFile)
}

func runOnce(ctx context.Context, token, out string, dryRun, full, validate bool) int {
	start := time.Now()
	bundleDir := filepath.Join(out, "okf")
	cache := OpenCache(filepath.Join(out, "cache"))
	statePath := filepath.Join(out, "state.json")
	state := LoadState(statePath)
	client := NewClient(token)

	snap, err := Fetch(ctx, client, cache, full)
	if err != nil {
		log.Printf("fetch failed: %v", err)
		return 1
	}
	if err := cache.Save(); err != nil {
		log.Printf("cache save failed: %v", err)
	}
	snap.Plan()
	bundle, entries := snap.Build(state, start)
	log.Printf("read %d pages (%d bodies fetched, %d API calls); bundle has %d files",
		len(snap.Docs), snap.Fetched, client.Calls, len(bundle.Files))

	if validate {
		findings := ValidateFiles(bundle.Files)
		for _, f := range findings {
			log.Printf("okf: %s", f)
		}
		if len(findings) > 0 {
			log.Printf("okf validation: %d finding(s); not writing", len(findings))
			return 1
		}
		log.Printf("okf validation: clean")
	}

	created, updated, removed, err := bundle.Apply(bundleDir, dryRun)
	if err != nil {
		log.Printf("write failed: %v", err)
		return 1
	}
	if !dryRun {
		if err := os.WriteFile(filepath.Join(out, "okf-base.yaml"), []byte(okflintManifest), 0o644); err != nil {
			log.Printf("manifest write failed: %v", err)
		}
	}
	verb := "wrote"
	if dryRun {
		verb = "would write"
	}
	log.Printf("%s %s: %d new, %d changed, %d removed (%s)", verb, bundleDir, created, updated, removed, time.Since(start).Round(time.Millisecond))
	if dryRun {
		return 0
	}
	state.Pages = map[string]StatePage{}
	for _, d := range snap.Docs {
		state.Pages[d.ID] = StatePage{Edited: d.Edited.UTC().Format(time.RFC3339Nano), File: d.File, Title: d.Title}
	}
	state.Log = entries
	state.LastRun = start.UTC().Format(time.RFC3339)
	if err := state.Save(statePath); err != nil {
		log.Printf("state save failed: %v", err)
		return 1
	}
	return 0
}
